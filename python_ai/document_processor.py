"""
LAMLA Guide AI - High-Power Python Slide & Document Processing Core
Slogan: "It's Never Too Late To Study."

Specialized in:
- Complete PowerPoint (.pptx) extraction across every slide from start to finish:
  titles, bullet hierarchy, tables, charts, SmartArt diagrams (ppt/diagrams/data*.xml),
  lecturer speaker notes, and embedded slide image OCR when slides are visual/scanned
- Complete PDF (.pdf) page-by-page extraction with structural layout, tables, and embedded image OCR
- Complete Word (.docx) extraction preserving headings, paragraphs, lists, and tables
- Image / Whiteboard photos (.jpg, .png, .webp) OCR through Gemini Vision
- Honest extraction coverage verification (identifies any unreadable/image-only pages or slides)
"""

import os
import re
import math
import io
import zipfile
import xml.etree.ElementTree as ET
from typing import List, Dict, Any, Optional, Tuple

try:
    import pymupdf
    HAS_PYMUPDF = True
except ImportError:
    try:
        import fitz as pymupdf
        HAS_PYMUPDF = True
    except ImportError:
        HAS_PYMUPDF = False

import pypdf
import docx
from pptx import Presentation


class DocumentProcessor:
    def __init__(self, chunk_size: int = 1500, chunk_overlap: int = 250):
        self.chunk_size = chunk_size
        self.chunk_overlap = chunk_overlap

    def clean_text(self, text: str) -> str:
        """Cleans artifacts commonly generated by OCR, weird encodings, and messy slides."""
        if not text:
            return ""
        cleaned = re.sub(r"[~^|`]{2,}", " ", text)
        cleaned = re.sub(r"\n{3,}", "\n\n", cleaned)
        cleaned = re.sub(r"[ \t]{2,}", " ", cleaned)
        cleaned = re.sub(r"(\w+)-\s*\n\s*(\w+)", r"\1\2", cleaned)
        return cleaned.strip()

    @staticmethod
    def _extract_smartart_from_pptx_zip(file_path_or_bytes: Any) -> Dict[int, List[str]]:
        """
        Extracts SmartArt / Diagram text from ppt/diagrams/data*.xml and maps relationships
        to slides so flowcharts and SmartArt graphics inside PowerPoint are never lost.
        """
        diagram_texts: Dict[int, List[str]] = {}
        try:
            zf = (
                zipfile.ZipFile(file_path_or_bytes, "r")
                if isinstance(file_path_or_bytes, (str, os.PathLike))
                else zipfile.ZipFile(io.BytesIO(file_path_or_bytes), "r")
            )
            with zf:
                names = zf.namelist()
                data_files = sorted(
                    [n for n in names if re.match(r"^ppt/diagrams/data\d+\.xml$", n, re.I)]
                )
                for idx, df in enumerate(data_files, start=1):
                    raw_xml = zf.read(df).decode("utf-8", errors="ignore")
                    tokens = [
                        t.strip()
                        for t in re.findall(r"<a:t\b[^>]*>(.*?)</a:t>", raw_xml, re.S)
                        if t and t.strip()
                    ]
                    deduped = []
                    for tok in tokens:
                        if tok not in deduped:
                            deduped.append(tok)
                    if deduped:
                        diagram_texts[idx] = deduped
        except Exception:
            pass
        return diagram_texts

    def process_pptx(self, file_path_or_bytes: Any) -> Dict[str, Any]:
        """
        Parses an entire PowerPoint presentation (.pptx) from first slide to last:
        - Preserves slide numbers, titles, hierarchical bullets, tables, charts, SmartArt diagrams, and speaker notes
        - Uses Vision OCR for image-only/diagram-only slides when needed
        - Produces an honest coverage report if any slide could not be fully transcribed
        """
        if isinstance(file_path_or_bytes, (str, os.PathLike)):
            prs = Presentation(file_path_or_bytes)
            filename = os.path.basename(str(file_path_or_bytes))
        else:
            prs = Presentation(io.BytesIO(file_path_or_bytes))
            filename = "presentation.pptx"

        smartart_map = self._extract_smartart_from_pptx_zip(file_path_or_bytes)
        slides_data: List[Dict[str, Any]] = []
        full_text_parts: List[str] = []
        unreadable_slides: List[int] = []
        ocr_calls_made = 0

        for slide_index, slide in enumerate(prs.slides, start=1):
            slide_title = ""
            slide_body_texts: List[str] = []
            speaker_notes = ""
            image_blobs: List[Tuple[bytes, str]] = []

            if slide.shapes.title and slide.shapes.title.text:
                slide_title = slide.shapes.title.text.strip()

            def _extract_shape_content(target_shape: Any, texts_list: List[str]) -> None:
                # 1. Text frames with paragraph indentation levels
                if getattr(target_shape, "has_text_frame", False):
                    para_lines = []
                    for para in target_shape.text_frame.paragraphs:
                        p_txt = para.text.strip()
                        if not p_txt:
                            continue
                        lvl = getattr(para, "level", 0) or 0
                        prefix = "  " * min(lvl, 3) + ("• " if lvl > 0 else "")
                        para_lines.append(f"{prefix}{p_txt}")
                    if para_lines:
                        texts_list.append("\n".join(para_lines))

                # 2. Tables (formatted as structured Markdown tables)
                if getattr(target_shape, "has_table", False):
                    table_rows = []
                    for r_idx, row in enumerate(target_shape.table.rows):
                        row_cells = [
                            re.sub(r"\s+", " ", cell.text.strip())
                            for cell in row.cells
                        ]
                        if any(row_cells):
                            table_rows.append("| " + " | ".join(c or "-" for c in row_cells) + " |")
                            if r_idx == 0:
                                sep = "| " + " | ".join("---" for _ in row_cells) + " |"
                                table_rows.append(sep)
                    if table_rows:
                        texts_list.append("[Table Data]:\n" + "\n".join(table_rows))

                # 3. Charts (extract chart title, categories, and series data)
                if getattr(target_shape, "has_chart", False):
                    try:
                        chart = target_shape.chart
                        c_parts = []
                        if getattr(chart, "has_title", False) and chart.chart_title.has_text_frame:
                            c_title = chart.chart_title.text_frame.text.strip()
                            if c_title:
                                c_parts.append(f"Chart Title: {c_title}")
                        for series in getattr(chart, "series", []):
                            s_name = getattr(series, "name", "") or "Series"
                            vals = [str(v) for v in (getattr(series, "values", []) or [])[:12] if v is not None]
                            if vals:
                                c_parts.append(f"{s_name}: {', '.join(vals)}")
                        if c_parts:
                            texts_list.append("[Chart / Graph]: " + " | ".join(c_parts))
                    except Exception:
                        pass

                # 4. Embedded pictures/diagrams (collect blob for OCR if slide text is sparse)
                try:
                    if hasattr(target_shape, "image") and target_shape.image and target_shape.image.blob:
                        ext = (getattr(target_shape.image, "ext", "jpeg") or "jpeg").lower()
                        mime = f"image/{'jpeg' if ext in ('jpg', 'jpeg') else ext}"
                        if len(target_shape.image.blob) > 4096:
                            image_blobs.append((target_shape.image.blob, mime))
                except Exception:
                    pass

                # 5. Recurse into group shapes
                if hasattr(target_shape, "shapes"):
                    for sub_shape in target_shape.shapes:
                        _extract_shape_content(sub_shape, texts_list)

            for shape in slide.shapes:
                if shape == slide.shapes.title:
                    continue
                _extract_shape_content(shape, slide_body_texts)

            # Attach SmartArt diagram text if associated with this slide index
            if slide_index in smartart_map:
                smart_items = " -> ".join(smartart_map[slide_index])
                slide_body_texts.append(f"[Diagram / Process Flow]: {smart_items}")

            if slide.has_notes_slide and slide.notes_slide.notes_text_frame:
                speaker_notes = slide.notes_slide.notes_text_frame.text.strip()

            slide_text = self.clean_text("\n".join(slide_body_texts))

            # If slide has embedded image(s)/diagram(s) but very little text, run Vision OCR (up to 6 slides per deck for speed)
            if len(slide_text) < 40 and image_blobs and ocr_calls_made < 6:
                try:
                    import base64
                    from ai_engine import PythonAIEngine
                    engine = PythonAIEngine()
                    largest_blob, blob_mime = max(image_blobs, key=lambda x: len(x[0]))
                    b64_img = base64.b64encode(largest_blob).decode("utf-8")
                    ocr_prompt = (
                        "Transcribe all text, labels, equations, table cells, and explain the diagram/chart "
                        "shown on this presentation slide image with complete academic accuracy."
                    )
                    ocr_text = engine.call_gemini_vision(ocr_prompt, image_base64=b64_img, mime_type=blob_mime)
                    ocr_calls_made += 1
                    if ocr_text and len(ocr_text.strip()) > 15:
                        slide_text = (slide_text + "\n[Visual/Diagram OCR]: " + ocr_text.strip()).strip()
                except Exception:
                    pass

            if not slide_title and slide_text:
                first_ln = slide_text.split("\n", 1)[0].strip("•-*# ")[:80]
                if first_ln:
                    slide_title = first_ln

            if len(slide_text) < 10 and not slide_title and not speaker_notes:
                unreadable_slides.append(slide_index)
                slide_text = (
                    "[Note: This slide contains visual/graphical elements with minimal selectable text. "
                    "Refer to the original slide visual in the presentation.]"
                )

            combined_slide_repr = f"--- Slide {slide_index}: {slide_title or f'Slide {slide_index}'} ---\n{slide_text}"
            if speaker_notes:
                combined_slide_repr += f"\n[Lecturer Note: {speaker_notes}]"

            full_text_parts.append(combined_slide_repr)
            slides_data.append({
                "slide_number": slide_index,
                "title": slide_title or f"Slide {slide_index}",
                "content": slide_text,
                "speaker_notes": speaker_notes,
                "full_slide_text": combined_slide_repr,
                "has_visual_warning": slide_index in unreadable_slides,
            })

        if unreadable_slides:
            nums_str = ", ".join(str(n) for n in unreadable_slides)
            full_text_parts.append(
                f"\n[Extraction Honesty Notice: Slide(s) {nums_str} contained predominantly non-text graphics or "
                f"unreadable scans where full text could not be extracted automatically.]"
            )

        full_document_text = "\n\n".join(full_text_parts)
        processed_count = max(len(prs.slides) - len(unreadable_slides), 0)
        coverage_pct = (processed_count / max(len(prs.slides), 1)) * 100.0 if prs.slides else 100.0

        return {
            "document_type": "pptx",
            "title": filename,
            "total_slides": len(prs.slides),
            "slides": slides_data,
            "unreadable_slides": unreadable_slides,
            "coverage_percentage": round(coverage_pct, 1),
            "full_text": full_document_text,
            "key_concepts": self.extract_key_concepts(full_document_text),
        }

    def process_pdf(self, file_path_or_bytes: Any) -> Dict[str, Any]:
        """
        Parses a PDF document (.pdf) page by page from start to finish with full text,
        multi-column layout preservation, vector table extraction, embedded image OCR fallback
        for scanned pages, and honest coverage reporting.
        """
        filename = (
            os.path.basename(str(file_path_or_bytes))
            if isinstance(file_path_or_bytes, (str, os.PathLike))
            else "document.pdf"
        )

        pages_data: List[Dict[str, Any]] = []
        full_text_parts: List[str] = []
        unreadable_pages: List[int] = []
        ocr_calls_made = 0
        total_pages = 0

        # Preference 1: PyMuPDF (fitz) for vector tables & block layout
        if HAS_PYMUPDF:
            try:
                if isinstance(file_path_or_bytes, (str, os.PathLike)):
                    doc = pymupdf.open(file_path_or_bytes)
                else:
                    raw_bytes = file_path_or_bytes if isinstance(file_path_or_bytes, bytes) else file_path_or_bytes.read()
                    doc = pymupdf.open(stream=raw_bytes, filetype="pdf")

                total_pages = len(doc)
                for page_index in range(1, total_pages + 1):
                    page = doc[page_index - 1]
                    page_text = page.get_text("text") or ""

                    # Extract structured vector tables if present
                    table_markdown_blocks = []
                    try:
                        if hasattr(page, "find_tables"):
                            tabs = page.find_tables()
                            for t_idx, tab in enumerate(tabs, start=1):
                                t_data = tab.extract()
                                if t_data and len(t_data) >= 1:
                                    t_rows = []
                                    for r_idx, row in enumerate(t_data):
                                        clean_row = [re.sub(r"\s+", " ", str(c or "").strip()) for c in row]
                                        if any(clean_row):
                                            t_rows.append("| " + " | ".join(c or "-" for c in clean_row) + " |")
                                            if r_idx == 0:
                                                t_rows.append("| " + " | ".join("---" for _ in clean_row) + " |")
                                    if t_rows:
                                        table_markdown_blocks.append(f"[Table {t_idx}]:\n" + "\n".join(t_rows))
                    except Exception:
                        pass

                    if table_markdown_blocks:
                        page_text = page_text + "\n\n" + "\n\n".join(table_markdown_blocks)

                    cleaned = self.clean_text(page_text)

                    # Vision OCR for scanned or image-dominated pages
                    if len(cleaned) < 30 and ocr_calls_made < 5:
                        try:
                            img_list = page.get_images()
                            if img_list:
                                xref = img_list[0][0]
                                base_img = doc.extract_image(xref)
                                img_bytes = base_img.get("image")
                                img_ext = base_img.get("ext", "png").lower()
                                if img_bytes and len(img_bytes) > 2048:
                                    import base64
                                    from ai_engine import PythonAIEngine
                                    engine = PythonAIEngine()
                                    b64_img = base64.b64encode(img_bytes).decode("utf-8")
                                    mime = f"image/{'jpeg' if img_ext in ('jpg', 'jpeg') else img_ext}"
                                    ocr_txt = engine.call_gemini_vision(
                                        "Transcribe all academic text, headings, formulas, and diagram labels from this page with 100% precision.",
                                        image_base64=b64_img,
                                        mime_type=mime,
                                    )
                                    ocr_calls_made += 1
                                    if ocr_txt and len(ocr_txt.strip()) > 15:
                                        cleaned = (cleaned + "\n" + self.clean_text(ocr_txt)).strip()
                        except Exception:
                            pass

                    if len(cleaned) < 15:
                        unreadable_pages.append(page_index)
                        cleaned = (
                            f"[Note: Page {page_index} appears to be a scanned image or graphic whose text "
                            f"could not be fully extracted.]"
                        )

                    lines = [l.strip() for l in cleaned.split("\n") if l.strip()]
                    page_title = lines[0][:80] if lines else f"Page {page_index}"
                    page_repr = f"--- Page {page_index}: {page_title} ---\n{cleaned}"
                    full_text_parts.append(page_repr)

                    pages_data.append({
                        "page_number": page_index,
                        "title": page_title,
                        "content": cleaned,
                        "full_page_text": page_repr,
                        "has_visual_warning": page_index in unreadable_pages,
                    })

                doc.close()
            except Exception:
                # If PyMuPDF encounter unexpected error, fallback to pypdf
                pages_data.clear()
                full_text_parts.clear()
                unreadable_pages.clear()

        # Preference 2: pypdf fallback
        if not pages_data:
            if isinstance(file_path_or_bytes, (str, os.PathLike)):
                reader = pypdf.PdfReader(file_path_or_bytes)
            else:
                reader = pypdf.PdfReader(io.BytesIO(file_path_or_bytes if isinstance(file_path_or_bytes, bytes) else file_path_or_bytes.read()))

            total_pages = len(reader.pages)
            for page_index, page in enumerate(reader.pages, start=1):
                try:
                    extracted = page.extract_text() or ""
                except Exception:
                    extracted = ""
                cleaned = self.clean_text(extracted)

                if len(cleaned) < 30 and ocr_calls_made < 5:
                    try:
                        imgs = getattr(page, "images", []) or []
                        if imgs:
                            import base64
                            from ai_engine import PythonAIEngine
                            engine = PythonAIEngine()
                            first_img = imgs[0]
                            b64_img = base64.b64encode(first_img.data).decode("utf-8")
                            ext = (first_img.name.rsplit(".", 1)[-1].lower() if "." in first_img.name else "jpeg")
                            mime = f"image/{'jpeg' if ext in ('jpg', 'jpeg') else ext}"
                            ocr_txt = engine.call_gemini_vision(
                                "Transcribe all academic text, headings, tables, and diagram labels from this page.",
                                image_base64=b64_img,
                                mime_type=mime,
                            )
                            ocr_calls_made += 1
                            if ocr_txt and len(ocr_txt.strip()) > 15:
                                cleaned = (cleaned + "\n" + self.clean_text(ocr_txt)).strip()
                    except Exception:
                        pass

                if len(cleaned) < 15:
                    unreadable_pages.append(page_index)
                    cleaned = (
                        f"[Note: Page {page_index} appears to be a scanned image or graphic whose text "
                        f"could not be fully extracted.]"
                    )

                lines = [l.strip() for l in cleaned.split("\n") if l.strip()]
                page_title = lines[0][:80] if lines else f"Page {page_index}"
                page_repr = f"--- Page {page_index}: {page_title} ---\n{cleaned}"
                full_text_parts.append(page_repr)

                pages_data.append({
                    "page_number": page_index,
                    "title": page_title,
                    "content": cleaned,
                    "full_page_text": page_repr,
                    "has_visual_warning": page_index in unreadable_pages,
                })

        if unreadable_pages:
            p_str = ", ".join(str(p) for p in unreadable_pages)
            full_text_parts.append(
                f"\n[Extraction Honesty Notice: Page(s) {p_str} contained scanned images or non-selectable "
                f"graphics that could not be fully transcribed.]"
            )

        full_document_text = "\n\n".join(full_text_parts)
        processed_count = max(total_pages - len(unreadable_pages), 0)
        coverage_pct = (processed_count / max(total_pages, 1)) * 100.0 if total_pages > 0 else 100.0

        return {
            "document_type": "pdf",
            "title": filename,
            "total_pages": total_pages,
            "pages": pages_data,
            "unreadable_pages": unreadable_pages,
            "coverage_percentage": round(coverage_pct, 1),
            "full_text": full_document_text,
            "key_concepts": self.extract_key_concepts(full_document_text),
        }

    def process_docx(self, file_path_or_bytes: Any) -> Dict[str, Any]:
        """
        Parses a Word document (.docx) preserving headings, paragraphs, and tables in sequence.
        """
        if isinstance(file_path_or_bytes, (str, os.PathLike)):
            doc = docx.Document(file_path_or_bytes)
            filename = os.path.basename(str(file_path_or_bytes))
        else:
            doc = docx.Document(io.BytesIO(file_path_or_bytes))
            filename = "document.docx"

        sections_data = []
        current_section: Dict[str, Any] = {"title": "Introduction", "paragraphs": []}
        full_text_parts = []

        for para in doc.paragraphs:
            text = para.text.strip()
            if not text:
                continue

            if para.style and para.style.name and para.style.name.startswith("Heading"):
                if current_section["paragraphs"]:
                    sections_data.append(current_section)
                current_section = {"title": text, "paragraphs": []}
            else:
                current_section["paragraphs"].append(text)

            full_text_parts.append(text)

        if current_section["paragraphs"]:
            sections_data.append(current_section)

        for tbl_idx, table in enumerate(doc.tables, start=1):
            t_rows = []
            for r_idx, row in enumerate(table.rows):
                cells = [re.sub(r"\s+", " ", c.text.strip()) for c in row.cells]
                if any(cells):
                    t_rows.append("| " + " | ".join(c or "-" for c in cells) + " |")
                    if r_idx == 0:
                        t_rows.append("| " + " | ".join("---" for _ in cells) + " |")
            if t_rows:
                sections_data.append({
                    "title": f"Table {tbl_idx}",
                    "paragraphs": ["[Table Data]:\n" + "\n".join(t_rows)],
                })

        structured_parts = []
        for idx, sec in enumerate(sections_data, start=1):
            body = "\n".join(sec["paragraphs"])
            structured_parts.append(f"--- Slide {idx}: {sec['title']} ---\n{body}")

        full_document_text = "\n\n".join(structured_parts) if structured_parts else "\n\n".join(full_text_parts)

        return {
            "document_type": "docx",
            "title": filename,
            "total_sections": len(sections_data),
            "total_slides": len(sections_data),
            "sections": sections_data,
            "full_text": full_document_text,
            "key_concepts": self.extract_key_concepts(full_document_text[:80000]),
        }

    def process_text(self, text: str, title: str = "Pasted Notes") -> Dict[str, Any]:
        """Parses plain text, notes, or Markdown while preserving or adding Slide/Section markers."""
        cleaned = self.clean_text(text)
        chunks = self.chunk_document(cleaned, {"doc_title": title})
        has_markers = bool(re.search(r"---\s*(?:Slide|Page)\s*\d+", cleaned))
        if not has_markers and len(chunks) > 1:
            marked_parts = []
            for c in chunks:
                first_line = c["text"].split("\n", 1)[0].strip("# ").strip()[:70] or f"Section {c['chunk_id']}"
                marked_parts.append(f"--- Slide {c['chunk_id']}: {first_line} ---\n{c['text']}")
            structured_text = "\n\n".join(marked_parts)
        else:
            structured_text = cleaned

        return {
            "document_type": "text",
            "title": title,
            "total_chunks": len(chunks),
            "chunks": chunks,
            "full_text": structured_text,
            "key_concepts": self.extract_key_concepts(cleaned[:80000]),
        }

    def process_image(self, file_path_or_bytes: Any, filename: str = "Slide Image") -> Dict[str, Any]:
        """
        Parses an image or slide photo using Gemini Vision OCR with full accuracy.
        """
        import base64
        if isinstance(file_path_or_bytes, (str, os.PathLike)):
            with open(file_path_or_bytes, "rb") as f:
                raw_bytes = f.read()
            name = os.path.basename(str(file_path_or_bytes))
        else:
            raw_bytes = file_path_or_bytes
            name = filename

        b64 = base64.b64encode(raw_bytes).decode("utf-8")
        ext = name.split(".")[-1].lower() if "." in name else "jpeg"
        mime = f"image/{'jpeg' if ext in ['jpg', 'jpeg'] else ext}"

        try:
            from ai_engine import PythonAIEngine
            engine = PythonAIEngine()
            prompt = (
                "Transcribe all readable text, titles, bullet points, mechanisms, classifications, tables, "
                "formulas, and diagram descriptions from this study material slide with 100% academic precision."
            )
            extracted_text = engine.call_gemini_vision(prompt, image_base64=b64, mime_type=mime)
        except Exception as e:
            extracted_text = (
                f"Slide Image: {name}\n"
                f"[Extraction Honesty Notice: Automatic Vision OCR was unable to transcribe this image ({str(e)}).]"
            )

        return {
            "document_type": "image",
            "title": name,
            "total_slides": 1,
            "slides": [{
                "slide_number": 1,
                "title": name,
                "content": extracted_text,
                "full_slide_text": f"--- Slide 1: {name} ---\n{extracted_text}",
            }],
            "full_text": f"--- Slide 1: {name} ---\n{extracted_text}",
            "key_concepts": self.extract_key_concepts(extracted_text),
        }

    def chunk_document(self, text: str, source_metadata: Dict[str, Any] = None) -> List[Dict[str, Any]]:
        """Splits text into overlapping semantic chunks for LLM token boundaries."""
        cleaned = self.clean_text(text)
        paragraphs = cleaned.split("\n\n")

        chunks = []
        current_chunk = []
        current_length = 0
        chunk_index = 1

        for para in paragraphs:
            para_len = len(para)
            if current_length + para_len > self.chunk_size and current_chunk:
                chunk_text = "\n\n".join(current_chunk)
                chunks.append({
                    "chunk_id": chunk_index,
                    "text": chunk_text,
                    "character_count": len(chunk_text),
                    "estimated_tokens": math.ceil(len(chunk_text) / 4),
                    "metadata": source_metadata or {},
                })
                chunk_index += 1
                current_chunk = [para]
                current_length = para_len
            else:
                current_chunk.append(para)
                current_length += para_len

        if current_chunk:
            chunk_text = "\n\n".join(current_chunk)
            chunks.append({
                "chunk_id": chunk_index,
                "text": chunk_text,
                "character_count": len(chunk_text),
                "estimated_tokens": math.ceil(len(chunk_text) / 4),
                "metadata": source_metadata or {},
            })

        return chunks

    def extract_key_concepts(self, text: str) -> List[str]:
        """Extracts genuine academic concepts while ignoring university/department/admin headers."""
        admin_words = {
            "University", "Department", "Faculty", "College", "School", "Institute",
            "Lecturer", "Professor", "Course", "Slide", "Page", "Table", "Welcome",
        }
        candidates = re.findall(r"\b[A-Z][a-zA-Z0-9\-]+(?:\s+[A-Z][a-zA-Z0-9\-]+)+\b", text)
        unique: List[str] = []
        for c in candidates:
            if any(aw.lower() in c.lower() for aw in admin_words):
                continue
            if c not in unique and 4 < len(c) <= 60:
                unique.append(c)
        return unique[:25]
