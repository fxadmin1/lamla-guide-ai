"""
LAMLA Guide AI - High-Power Python Slide & Document Processing Core
Slogan: "It's Never Too Late To Study."

Specialized in:
- PowerPoint (.pptx) extraction with slide numbers, titles, bullet hierarchy & lecturer notes
- PDF (.pdf) page-by-page extraction with structural layout
- Word (.docx) documents with headings, tables and lists
- Image / Whiteboard photos (.jpg, .png) OCR through Gemini Vision
- Text cleaning, semantic sliding-window chunking, and key concept distillation
"""

import os
import re
import math
import io
from typing import List, Dict, Any, Optional

import pypdf
import docx
from pptx import Presentation

class DocumentProcessor:
    def __init__(self, chunk_size: int = 1500, chunk_overlap: int = 250):
        self.chunk_size = chunk_size
        self.chunk_overlap = chunk_overlap

    def clean_text(self, text: str) -> str:
        """Cleans artifacts commonly generated by OCR, weird encodings, and messy slides."""
        if not text:
            return ""
        # Remove consecutive repetitive weird symbols
        cleaned = re.sub(r'[~^|`]{2,}', ' ', text)
        # Normalize excessive newlines and spaces
        cleaned = re.sub(r'\n{3,}', '\n\n', cleaned)
        cleaned = re.sub(r'[ \t]{2,}', ' ', cleaned)
        # Fix broken words across line breaks (e.g., photo- \n synthesis -> photosynthesis)
        cleaned = re.sub(r'(\w+)-\s*\n\s*(\w+)', r'\1\2', cleaned)
        return cleaned.strip()

    def process_pptx(self, file_path_or_bytes: Any) -> Dict[str, Any]:
        """
        Parses a PowerPoint presentation (.pptx).
        Preserves slide numbers, slide titles, body shapes, tables, and lecturer notes.
        """
        if isinstance(file_path_or_bytes, (str, os.PathLike)):
            prs = Presentation(file_path_or_bytes)
            filename = os.path.basename(str(file_path_or_bytes))
        else:
            prs = Presentation(io.BytesIO(file_path_or_bytes))
            filename = "presentation.pptx"

        slides_data = []
        full_text_parts = []

        for slide_index, slide in enumerate(prs.slides, start=1):
            slide_title = ""
            slide_body_texts = []
            speaker_notes = ""

            # Extract title if present
            if slide.shapes.title and slide.shapes.title.text:
                slide_title = slide.shapes.title.text.strip()

            def _extract_shape_text(target_shape, texts_list):
                if target_shape.has_text_frame:
                    t = target_shape.text_frame.text.strip()
                    if t:
                        texts_list.append(t)
                elif target_shape.has_table:
                    table_rows = []
                    for row in target_shape.table.rows:
                        row_cells = [cell.text.strip() for cell in row.cells if cell.text.strip()]
                        if row_cells:
                            table_rows.append(" | ".join(row_cells))
                    if table_rows:
                        texts_list.append("\n".join(table_rows))
                elif hasattr(target_shape, "shapes"):
                    for sub_shape in target_shape.shapes:
                        _extract_shape_text(sub_shape, texts_list)

            # Iterate over shapes in slide (recursively extracting grouped shapes and tables)
            for shape in slide.shapes:
                if shape == slide.shapes.title:
                    continue
                _extract_shape_text(shape, slide_body_texts)

            # Extract lecturer speaker notes
            if slide.has_notes_slide and slide.notes_slide.notes_text_frame:
                speaker_notes = slide.notes_slide.notes_text_frame.text.strip()

            slide_text = "\n".join(slide_body_texts)
            combined_slide_repr = f"--- Slide {slide_index}: {slide_title or 'Untitled'} ---\n{slide_text}"
            if speaker_notes:
                combined_slide_repr += f"\n[Lecturer Note: {speaker_notes}]"

            full_text_parts.append(combined_slide_repr)

            slides_data.append({
                "slide_number": slide_index,
                "title": slide_title or f"Slide {slide_index}",
                "content": slide_text,
                "speaker_notes": speaker_notes,
                "full_slide_text": combined_slide_repr
            })

        full_document_text = "\n\n".join(full_text_parts)

        return {
            "document_type": "pptx",
            "title": filename,
            "total_slides": len(prs.slides),
            "slides": slides_data,
            "full_text": full_document_text,
            "key_concepts": self.extract_key_concepts(full_document_text)
        }

    def process_pdf(self, file_path_or_bytes: Any) -> Dict[str, Any]:
        """
        Parses a PDF document (.pdf) page by page with full text and page references.
        """
        if isinstance(file_path_or_bytes, (str, os.PathLike)):
            reader = pypdf.PdfReader(file_path_or_bytes)
            filename = os.path.basename(str(file_path_or_bytes))
        else:
            reader = pypdf.PdfReader(io.BytesIO(file_path_or_bytes))
            filename = "document.pdf"

        pages_data = []
        full_text_parts = []

        for page_index, page in enumerate(reader.pages, start=1):
            extracted = page.extract_text() or ""
            cleaned = self.clean_text(extracted)
            
            # Infer page title from first line if feasible
            lines = [l.strip() for l in cleaned.split("\n") if l.strip()]
            page_title = lines[0][:80] if lines else f"Page {page_index}"

            page_repr = f"--- Page {page_index}: {page_title} ---\n{cleaned}"
            full_text_parts.append(page_repr)

            pages_data.append({
                "page_number": page_index,
                "title": page_title,
                "content": cleaned,
                "full_page_text": page_repr
            })

        full_document_text = "\n\n".join(full_text_parts)

        return {
            "document_type": "pdf",
            "title": filename,
            "total_pages": len(reader.pages),
            "pages": pages_data,
            "full_text": full_document_text,
            "key_concepts": self.extract_key_concepts(full_document_text)
        }

    def process_docx(self, file_path_or_bytes: Any) -> Dict[str, Any]:
        """
        Parses a Word document (.docx) preserving headings and paragraphs.
        """
        if isinstance(file_path_or_bytes, (str, os.PathLike)):
            doc = docx.Document(file_path_or_bytes)
            filename = os.path.basename(str(file_path_or_bytes))
        else:
            doc = docx.Document(io.BytesIO(file_path_or_bytes))
            filename = "document.docx"

        sections_data = []
        current_section = {"title": "Introduction", "paragraphs": []}
        full_text_parts = []

        for para in doc.paragraphs:
            text = para.text.strip()
            if not text:
                continue

            if para.style.name.startswith("Heading"):
                if current_section["paragraphs"]:
                    sections_data.append(current_section)
                current_section = {"title": text, "paragraphs": []}
            else:
                current_section["paragraphs"].append(text)
            
            full_text_parts.append(text)

        if current_section["paragraphs"]:
            sections_data.append(current_section)

        # Also extract DOCX tables so no tabular exam content is missed
        for tbl_idx, table in enumerate(doc.tables, start=1):
            t_rows = []
            for row in table.rows:
                cells = [c.text.strip() for c in row.cells if c.text.strip()]
                if cells:
                    t_rows.append(" | ".join(cells))
            if t_rows:
                sections_data.append({
                    "title": f"Table {tbl_idx}",
                    "paragraphs": t_rows,
                })

        structured_parts = []
        for idx, sec in enumerate(sections_data, start=1):
            body = "\n".join(sec["paragraphs"])
            structured_parts.append(f"--- Slide {idx}: {sec['title']} ---\n{body}")

        full_document_text = "\n\n".join(structured_parts) if structured_parts else "\n\n".join(full_text_parts)

        return {
            "document_type": "docx",
            "title": filename,
            "total_sections": len(sections_data),
            "total_slides": len(sections_data),
            "sections": sections_data,
            "full_text": full_document_text,
            "key_concepts": self.extract_key_concepts(full_document_text[:80000])
        }

    def process_text(self, text: str, title: str = "Pasted Notes") -> Dict[str, Any]:
        """Parses plain text, notes, or Markdown while preserving or adding Slide/Section markers."""
        cleaned = self.clean_text(text)
        chunks = self.chunk_document(cleaned, {"doc_title": title})
        has_markers = bool(re.search(r"---\s*(?:Slide|Page)\s*\d+", cleaned))
        if not has_markers and len(chunks) > 1:
            marked_parts = []
            for c in chunks:
                first_line = c["text"].split("\n", 1)[0].strip("# ").strip()[:70] or f"Section {c['chunk_id']}"
                marked_parts.append(f"--- Slide {c['chunk_id']}: {first_line} ---\n{c['text']}")
            structured_text = "\n\n".join(marked_parts)
        else:
            structured_text = cleaned

        return {
            "document_type": "text",
            "title": title,
            "total_chunks": len(chunks),
            "chunks": chunks,
            "full_text": structured_text,
            "key_concepts": self.extract_key_concepts(cleaned[:80000])
        }

    def process_image(self, file_path_or_bytes: Any, filename: str = "Slide Image") -> Dict[str, Any]:
        """
        Parses an image or slide photo using Gemini Vision OCR with full accuracy.
        """
        import base64
        if isinstance(file_path_or_bytes, (str, os.PathLike)):
            with open(file_path_or_bytes, "rb") as f:
                raw_bytes = f.read()
            name = os.path.basename(str(file_path_or_bytes))
        else:
            raw_bytes = file_path_or_bytes
            name = filename

        b64 = base64.b64encode(raw_bytes).decode("utf-8")
        ext = name.split(".")[-1].lower() if "." in name else "jpeg"
        mime = f"image/{'jpeg' if ext in ['jpg', 'jpeg'] else ext}"
        
        try:
            from ai_engine import PythonAIEngine
            engine = PythonAIEngine()
            prompt = (
                "Transcribe all readable text, titles, bullet points, mechanisms, formulas, and "
                "diagram descriptions from this study material slide with 100% academic precision."
            )
            extracted_text = engine.call_gemini_vision(prompt, image_base64=b64, mime_type=mime)
        except Exception as e:
            extracted_text = f"Slide Image: {name}\n[Text transcription: {str(e)}]"

        return {
            "document_type": "image",
            "title": name,
            "total_slides": 1,
            "slides": [{
                "slide_number": 1,
                "title": name,
                "content": extracted_text,
                "full_slide_text": f"--- Slide 1: {name} ---\n{extracted_text}"
            }],
            "full_text": extracted_text,
            "key_concepts": self.extract_key_concepts(extracted_text)
        }

    def chunk_document(self, text: str, source_metadata: Dict[str, Any] = None) -> List[Dict[str, Any]]:
        """
        Splits text into overlapping semantic chunks for LLM token boundaries.
        """
        cleaned = self.clean_text(text)
        paragraphs = cleaned.split("\n\n")
        
        chunks = []
        current_chunk = []
        current_length = 0
        chunk_index = 1

        for para in paragraphs:
            para_len = len(para)
            if current_length + para_len > self.chunk_size and current_chunk:
                chunk_text = "\n\n".join(current_chunk)
                chunks.append({
                    "chunk_id": chunk_index,
                    "text": chunk_text,
                    "character_count": len(chunk_text),
                    "estimated_tokens": math.ceil(len(chunk_text) / 4),
                    "metadata": source_metadata or {}
                })
                chunk_index += 1
                current_chunk = [para]
                current_length = para_len
            else:
                current_chunk.append(para)
                current_length += para_len

        if current_chunk:
            chunk_text = "\n\n".join(current_chunk)
            chunks.append({
                "chunk_id": chunk_index,
                "text": chunk_text,
                "character_count": len(chunk_text),
                "estimated_tokens": math.ceil(len(chunk_text) / 4),
                "metadata": source_metadata or {}
            })

        return chunks

    def extract_key_concepts(self, text: str) -> List[str]:
        """Extracts key academic keywords, capitalized multi-word terms, and formulas."""
        candidates = re.findall(r'\b[A-Z][a-z]+(?:\s+[A-Z][a-z]+)+\b', text)
        unique = []
        for c in candidates:
            if c not in unique and len(c) > 4:
                unique.append(c)
        return unique[:15]
